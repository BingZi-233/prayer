/**
 * 毫秒时长的人读格式。全仓唯一出处。
 * 粒度取合并前三处里最细的一档:不足 1 分钟出「N 秒」(原 proactive 的行为),
 * 满 1 小时出「N 时」(原 reflection 的行为)。
 *
 * **已知瑕疵(不是 bug,别去"修"):** 档位切换按原值判、展示值另行四舍五入,
 * 所以在档位边界附近会出现 `59_500 → "60 秒"`、`3_599_999 → "60 分"`。
 * 触发窗口极小(分档 6 秒、秒档 500 毫秒),且合并前三处**都有**同样行为。
 * 改成 floor 会反过来把「1 分 59.9 秒」显示成「1 分」,得不偿失 —— 已接受。
 *
 * 另:`ms` 为负数或 NaN 时输出未定义(调用点均为配置值与指标,实际非负);
 * 空值由调用侧自行处理成「—」。
 */
export function formatDuration(ms: number): string {
  if (ms < 60_000) return `${Math.round(ms / 1000)} 秒`
  if (ms >= 3_600_000) {
    return `${(ms / 3_600_000).toFixed(ms % 3_600_000 ? 1 : 0)} 时`
  }
  return `${Math.round(ms / 60_000)} 分`
}
